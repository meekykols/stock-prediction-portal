import mongoose from 'mongoose';

const imageSchema = new mongoose.Schema({ url: String, publicId: String }, { _id: false });

// Single document (key: "main") that drives branding and contact details everywhere:
// the public site, the dashboard, the admin console and outgoing emails.
const siteConfigSchema = new mongoose.Schema(
  {
    key: { type: String, default: 'main', unique: true, immutable: true },
    siteName: { type: String, default: 'Prediction Web', trim: true },
    tagline: { type: String, default: 'AI-powered market and sports predictions', trim: true },
    description: { type: String, trim: true },
    logo: imageSchema,
    logoDark: imageSchema,
    favicon: imageSchema,
    contact: {
      email: { type: String, trim: true },
      supportEmail: { type: String, trim: true },
      phone: { type: String, trim: true },
      whatsapp: { type: String, trim: true },
      address: { type: String, trim: true },
      supportHours: { type: String, trim: true },
    },
    socials: {
      x: String,
      facebook: String,
      instagram: String,
      telegram: String,
      youtube: String,
      linkedin: String,
      tiktok: String,
    },
    currency: {
      code: { type: String, default: 'NGN' },
      symbol: { type: String, default: '₦' },
      locale: { type: String, default: 'en-NG' },
    },
    seo: {
      title: String,
      description: String,
      keywords: [String],
    },
    legal: {
      companyName: String,
      registrationNumber: String,
      disclaimer: {
        type: String,
        default:
          'Predictions are generated by statistical models and are not financial or betting advice. Past performance does not guarantee future results.',
      },
    },
    announcement: {
      enabled: { type: Boolean, default: false },
      text: String,
      link: String,
    },
    maintenanceMode: { type: Boolean, default: false },
  },
  {
    timestamps: true,
    toJSON: {
      transform(_doc, ret) {
        delete ret.__v;
        delete ret._id;
        delete ret.key;
        return ret;
      },
    },
  },
);

siteConfigSchema.statics.getSingleton = function getSingleton() {
  return this.findOneAndUpdate(
    { key: 'main' },
    { $setOnInsert: { key: 'main' } },
    { upsert: true, returnDocument: 'after', setDefaultsOnInsert: true },
  );
};

export const SiteConfig = mongoose.model('SiteConfig', siteConfigSchema);
